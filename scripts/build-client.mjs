import { readFile, writeFile } from 'node:fs/promises';
import { createSizing } from '../sizing.js';
import { createImageHistory } from '../image-history.js';
const root = new URL('../', import.meta.url);
const source = await readFile(new URL('client.source.js', root), 'utf8');
const marker = '/* SHARED_IMAGE_SIZING */';
if (source.split(marker).length !== 2) throw new Error('Expected exactly one sizing placeholder');
const historyMarker = '/* SHARED_IMAGE_HISTORY */';
if (source.split(historyMarker).length !== 2) throw new Error('Expected exactly one history placeholder');
const built = '// Generated by scripts/build-client.mjs. Edit client.source.js, sizing.js or image-history.js.\n'
  + source.replace(marker, `const sizing = (${createSizing.toString()})();`)
    .replace(historyMarker, `const history = (${createImageHistory.toString()})();`);
if (process.argv.includes('--check')) {
  if (await readFile(new URL('client.js', root), 'utf8') !== built) throw new Error('client.js is stale; run npm run build:client');
} else await writeFile(new URL('client.js', root), built);
